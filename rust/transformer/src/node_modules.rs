use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use itertools::Itertools;
use serde::Deserialize;
use serde_json::Value;

/// An npm package installed into a `node_modules` directory.
#[derive(Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct NpmPackage {
    pub name: String,
    pub version: String,
    /// The license as declared in the `package.json`.
    pub license: Option<String>,
}

#[derive(Deserialize)]
struct Manifest {
    name: Option<String>,
    version: Option<String>,
    license: Option<Value>,
    licenses: Option<Value>,
}

/// Find the npm packages installed below `root`.
///
/// A package is a directory directly inside a `node_modules` directory (or inside a scope
/// directory like `node_modules/@scope`) that contains a `package.json` with a name and a
/// version. Symlinks are not followed: package managers like pnpm link packages into place and
/// the targets are either found in the same store path or are store paths of their own.
pub fn scan(root: &Path) -> Result<Vec<NpmPackage>> {
    let mut packages = Vec::new();
    if !root
        .symlink_metadata()
        .is_ok_and(|metadata| metadata.is_dir())
    {
        return Ok(packages);
    }

    let mut directories = vec![root.to_path_buf()];
    while let Some(directory) = directories.pop() {
        if is_package_directory(&directory)
            && let Some(package) = read_manifest(&directory.join("package.json"))
        {
            packages.push(package);
        }
        for entry in fs::read_dir(&directory)
            .with_context(|| format!("Failed to read {}", directory.display()))?
        {
            let entry = entry
                .with_context(|| format!("Failed to read entry of {}", directory.display()))?;
            if entry.file_type()?.is_dir() {
                directories.push(entry.path());
            }
        }
    }

    packages.sort();
    packages.dedup();
    Ok(packages)
}

fn is_package_directory(directory: &Path) -> bool {
    let parent = directory.parent();
    let parent = match parent.and_then(Path::file_name) {
        Some(name) if name.as_encoded_bytes().starts_with(b"@") => parent.and_then(Path::parent),
        _ => parent,
    };
    parent
        .and_then(Path::file_name)
        .is_some_and(|name| name == "node_modules")
}

/// Read a `package.json`. Manifests that cannot be read or that miss a name or a version are
/// skipped because they do not describe an installed package.
fn read_manifest(path: &Path) -> Option<NpmPackage> {
    let content = fs::read(path).ok()?;
    let manifest: Manifest = serde_json::from_slice(&content).ok()?;
    let name = manifest.name.as_ref().filter(|s| !s.is_empty())?.clone();
    let version = manifest.version.as_ref().filter(|s| !s.is_empty())?.clone();
    Some(NpmPackage {
        name,
        version,
        license: declared_license(&manifest),
    })
}

/// The license of a manifest.
///
/// Old packages declare the license as an object (`{ "type": "MIT" }`) or as a list in the
/// `licenses` field. Like npm, interpret such a list as a choice between the licenses.
fn declared_license(manifest: &Manifest) -> Option<String> {
    let value = manifest.license.as_ref().or(manifest.licenses.as_ref())?;
    let names: Vec<&str> = match value {
        Value::Array(items) => items.iter().filter_map(license_name).collect(),
        other => license_name(other).into_iter().collect(),
    };
    match names.as_slice() {
        [] => None,
        [name] => Some((*name).to_string()),
        _ => Some(
            names
                .iter()
                .map(|name| {
                    if name.contains(' ') {
                        format!("({name})")
                    } else {
                        (*name).to_string()
                    }
                })
                .join(" OR "),
        ),
    }
}

fn license_name(value: &Value) -> Option<&str> {
    match value {
        Value::String(s) => Some(s.as_str()),
        Value::Object(object) => object.get("type").and_then(Value::as_str),
        _ => None,
    }
    .map(str::trim)
    .filter(|s| !s.is_empty())
}

#[cfg(test)]
mod tests {
    use super::*;

    use std::path::PathBuf;

    fn write(root: &Path, path: &str, content: &str) -> Result<()> {
        let path = root.join(path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, content)?;
        Ok(())
    }

    fn fixture(name: &str) -> PathBuf {
        let root =
            std::env::temp_dir().join(format!("bombon-node-modules-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        root
    }

    fn package(name: &str, version: &str, license: Option<&str>) -> NpmPackage {
        NpmPackage {
            name: name.to_string(),
            version: version.to_string(),
            license: license.map(ToString::to_string),
        }
    }

    #[test]
    fn scan_finds_installed_packages() -> Result<()> {
        let root = fixture("scan");
        write(
            &root,
            "package.json",
            r#"{"name": "app", "version": "1.0.0"}"#,
        )?;
        write(
            &root,
            "lib/node_modules/a/package.json",
            r#"{"name": "a", "version": "1.0.0", "license": "MIT"}"#,
        )?;
        // Nested `package.json` files of a package are not packages.
        write(
            &root,
            "lib/node_modules/a/dist/package.json",
            r#"{"name": "a-dist", "version": "1.0.0"}"#,
        )?;
        write(
            &root,
            "lib/node_modules/a/node_modules/b/package.json",
            r#"{"name": "b", "version": "2.0.0", "license": {"type": "ISC"}}"#,
        )?;
        write(
            &root,
            "lib/node_modules/@scope/c/package.json",
            r#"{"name": "@scope/c", "version": "3.0.0", "licenses": [{"type": "MIT"}, "Apache-2.0"]}"#,
        )?;
        // The pnpm layout.
        write(
            &root,
            "node_modules/.pnpm/d@4.0.0/node_modules/d/package.json",
            r#"{"name": "d", "version": "4.0.0", "license": "(MIT OR Apache-2.0)"}"#,
        )?;
        // No version, invalid JSON.
        write(&root, "node_modules/e/package.json", r#"{"name": "e"}"#)?;
        write(&root, "node_modules/f/package.json", "{")?;

        let packages = scan(&root)?;
        fs::remove_dir_all(&root)?;

        assert_eq!(
            packages,
            vec![
                package("@scope/c", "3.0.0", Some("MIT OR Apache-2.0")),
                package("a", "1.0.0", Some("MIT")),
                package("b", "2.0.0", Some("ISC")),
                package("d", "4.0.0", Some("(MIT OR Apache-2.0)")),
            ]
        );
        Ok(())
    }

    #[test]
    fn scan_ignores_non_directories() -> Result<()> {
        let root = fixture("file");
        write(&root, "file", "")?;
        let packages = scan(&root.join("file"))?;
        fs::remove_dir_all(&root)?;
        assert!(packages.is_empty());
        Ok(())
    }

    #[test]
    fn license_list_with_compound_license() {
        let manifest = Manifest {
            name: None,
            version: None,
            license: None,
            licenses: Some(serde_json::json!([
                "MIT",
                "GPL-2.0-only WITH Classpath-exception-2.0"
            ])),
        };
        assert_eq!(
            declared_license(&manifest).as_deref(),
            Some("MIT OR (GPL-2.0-only WITH Classpath-exception-2.0)")
        );
    }
}
